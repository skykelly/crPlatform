# 통계 대시보드 카드 정의. site/dashboard.py가 불러 팩트베이스(data/factbase.sqlite)에서 값을 계산한다.
#
# 식(expr)
#   S(표, 항목, d2, d3, 지역)  관측치 한 계열. 빈 분류는 "". 지역 기본값 "00"(전국)
#   add(a, b, ...)             연도별 합 (모든 항이 있는 연도만)
#   ratio(a, b, scale=100)     a / b × scale
#   either(a, b)               a가 없는 연도는 b로 채운다 (표가 연도별로 나뉜 경우)
#   real(a, cpi)               a ÷ (cpi / 100). 명목 금액을 2020년 물가로 바꾼다
# 카드 종류
#   line   연도별 선. proj=True 계열은 공식 추계(점선)
#   comp   구성비. parts의 합이 total(없으면 100)에 대한 비중
#   bars   범주별 값 (최근 연도 막대 + 처음 연도와 비교)
#   region 시도별 값 (식의 지역 자리를 시도로 바꿔 계산)
#   matrix 행 × 열 표 (최근 연도). share=True면 행 합계 대비 비중
#   real   명목·물가·실질 증감 표
# fmt: 소수 자리(dp), 단위(unit), 나누기(div). unit="time"은 분을 '시간:분'으로 표시


def S(t, m, d2="", d3="", g="00"):
    return {"op": "sel", "t": t, "m": m, "d2": d2, "d3": d3, "g": g}


def add(*a):
    return {"op": "add", "a": list(a)}


def ratio(a, b, scale=100):
    return {"op": "ratio", "a": a, "b": b, "scale": scale}


def either(*a):
    return {"op": "either", "a": list(a)}


def real(a, cpi):
    return {"op": "real", "a": a, "cpi": cpi}


